/**
 * Shared placement file format: a layout is expressed in physical millimetres,
 * never screenshot pixel coordinates. Imported files are validated, never eval'd.
 * Browser editor and Node CSS build use exactly the same compiler.
 */
export const PLACEMENT_VERSION=1;
export const PARTS=Object.freeze(["title","rules","results"]);
const SELECTOR=Object.freeze({
 title:".tt-title",
 rules:".tt-collage > .tt-content .tt-slip--lead",
 results:".tt-collage > .tt-content .tt-slip--results"
});
const CARD_KEY=/^(hero|room|monster|item|potion):([a-z0-9-]+)$/;
const LIMITS=Object.freeze({x:[0,90],y:[0,130],w:[10,90],h:[0,130]});
const own=(o,k)=>Object.prototype.hasOwnProperty.call(o,k);
const obj=o=>o!==null&&typeof o==="object"&&!Array.isArray(o);
const rounded=n=>Number(n.toFixed(2));
export function emptyPlacements(){return {version:PLACEMENT_VERSION,units:"mm",cards:{}};}
export function normalizePlacements(input){
 if(!obj(input)||input.version!==PLACEMENT_VERSION||input.units!=="mm"||!obj(input.cards))
  throw new Error("Expected Rogue Cards layout JSON (version 1, units mm, cards object).");
 const result=emptyPlacements();
 for(const [key,pieces] of Object.entries(input.cards)){
  if(!CARD_KEY.test(key))throw new Error("Invalid card key: "+key);
  if(!obj(pieces))throw new Error("Invalid card placements: "+key);
  const saved={};
  for(const [part,position] of Object.entries(pieces)){
   if(!PARTS.includes(part)||!obj(position))throw new Error("Invalid piece: "+key+"/"+part);
   const entry={};
   for(const [field,value]of Object.entries(position)){
    if(!own(LIMITS,field))throw new Error("Unexpected field: "+key+"/"+part+"/"+field);
    const [min,max]=LIMITS[field];
    if(typeof value!=="number"||!Number.isFinite(value)||value<min||value>max)
     throw new Error("Invalid mm value: "+key+"/"+part+"/"+field);
    entry[field]=rounded(value);
   }
   if(Object.keys(entry).length)saved[part]=entry;
  }
  if(Object.keys(saved).length)result.cards[key]=saved;
 }
 return result;
}
const mm=n=>String(n)+"mm";
export function placementCSS(input){
 const data=normalizePlacements(input);
 const lines=[
  "/* GENERATED by npm run layouts:build from data/card-placements.json.",
  "   Edit positions in layout-editor.html; do not hand-edit this stylesheet. */"
 ];
 for(const [key,pieces]of Object.entries(data.cards).sort(([a],[b])=>a.localeCompare(b))){
  const [,type,id]=key.match(CARD_KEY);
  const prefix='.tt-card.tt-paper-collage[data-type="'+type+'"][data-id="'+id+'"] ';
  for(const part of PARTS){
   const place=pieces[part];
   if(!place)continue;
   const decl=[];
   if(own(place,"x"))decl.push("left:"+mm(place.x),"right:auto");
   if(own(place,"y"))decl.push("top:"+mm(place.y),"bottom:auto");
   if(own(place,"w"))decl.push("width:"+mm(place.w),"max-width:none");
   // min-height rather than fixed height: copy stays readable when text wraps.
   if(own(place,"h"))decl.push("min-height:"+mm(place.h),"height:auto");
   lines.push(prefix+SELECTOR[part]+"{\n "+decl.join(";\n ")+";\n}");
  }
 }
 return lines.join("\n")+"\n";
}
