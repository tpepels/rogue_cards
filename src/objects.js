export const V2_OBJECT_COPIES=Object.freeze(V2_OBJECTS.flatMap(c=>Array.from({length:c.copies},()=>c)));
export const V2_OBJECTS_BY_FAMILY=Object.freeze(Object.fromEntries([...V2_ITEM_FAMILIES,"POTION"].map(kind=>[
 kind,Object.freeze(V2_OBJECTS.filter(card=>card.v2.kind===kind))
])));
export const V2_TAGS=Object.freeze([...new Set(V2_OBJECTS.flatMap(c=>c.v2.tags))].sort());
